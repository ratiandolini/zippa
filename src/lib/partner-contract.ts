/** მომხმარებლისთვის/PDF-სთვის ხილული ტექსტი — LEGAL REVIEW შენიშვნის გარეშე */
export function publicContractText(): string {
  return CONTRACT_CLAUSES.map((c) => `${c.title}\n${c.body}`).join("\n\n");
}

/** სტაბილური ჰეში ვერსია+ტექსტიდან — თანხმობის ჩანაწერში ინახება, რომ დამტკიცდეს "რას ეთანხმებოდა ზუსტად" */
export function contractContentHash(): string {
  return createHash("sha256").update(`${CONTRACT_VERSION}\n${publicContractText()}`).digest("hex");
}

/** დისპეჩერის review-გვერდისთვის — რომელი პუნქტები საჭიროებს იურისტის შემოწმებას */
